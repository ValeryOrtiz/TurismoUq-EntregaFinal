-- ============================================================================
-- A) AUDITORIA DE CAMBIOS SOBRE TARIFA (disparador de sentencia)
-- ----------------------------------------------------------------------------
-- Problema: un disparador de sentencia "puro" (sin FOR EACH ROW) se ejecuta
-- una sola vez por sentencia y NO tiene acceso a :OLD ni a :NEW, asi que por
-- si solo no puede saber el valor anterior y el nuevo.
-- Solucion: un COMPOUND TRIGGER. Tiene secciones de sentencia y de fila que
-- comparten variables:
--   BEFORE STATEMENT : una vez por sentencia -> numera la sentencia, toma
--                      quien (usuario BD, usuario SO, equipo, programa) y
--                      cuando (SYSTIMESTAMP).
--   AFTER EACH ROW   : solo copia :OLD y :NEW a una coleccion en memoria.
--   AFTER STATEMENT  : una vez por sentencia -> escribe toda la auditoria
--                      con un solo FORALL.
-- Un UPDATE que cambia 300 tarifas hace UNA insercion masiva y todas sus
-- filas quedan con el mismo id_sentencia y la misma fecha_hora.
-- Si la sentencia hace ROLLBACK, la auditoria tambien se deshace: solo queda
-- registro de los cambios que realmente se confirmaron.
-- ============================================================================
CREATE SEQUENCE SEQ_AUDITORIA_SENTENCIA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE AUDITORIA_TARIFA (
    auditoria_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sentencia    NUMBER        NOT NULL,
    operacion       VARCHAR2(6)   NOT NULL,
    habitacion_id   NUMBER        NOT NULL,
    temporada_id    NUMBER        NOT NULL,
    precio_anterior NUMBER(10,2),
    precio_nuevo    NUMBER(10,2),
    usuario_bd      VARCHAR2(128) NOT NULL,
    usuario_so      VARCHAR2(128),
    equipo          VARCHAR2(128),
    programa        VARCHAR2(128),
    fecha_hora      TIMESTAMP     NOT NULL,
    CONSTRAINT ck_aud_operacion CHECK (operacion IN ('INSERT','UPDATE','DELETE'))
);
-- Sin FK hacia TARIFA a proposito: la auditoria debe sobrevivir aunque la
-- tarifa se borre.
COMMENT ON TABLE AUDITORIA_TARIFA IS 'Auditoria de cambios en TARIFA: quien, cuando, valor anterior y nuevo (trg_tarifa_auditoria).';

CREATE OR REPLACE TRIGGER trg_tarifa_auditoria
FOR INSERT OR UPDATE OR DELETE ON TARIFA
COMPOUND TRIGGER

    TYPE t_fila IS RECORD (
        habitacion_id   NUMBER,
        temporada_id    NUMBER,
        precio_anterior NUMBER,
        precio_nuevo    NUMBER
    );
    TYPE t_filas IS TABLE OF t_fila INDEX BY PLS_INTEGER;

    g_filas        t_filas;
    g_id_sentencia NUMBER;
    g_operacion    VARCHAR2(6);
    g_usuario_bd   VARCHAR2(128);
    g_usuario_so   VARCHAR2(128);
    g_equipo       VARCHAR2(128);
    g_programa     VARCHAR2(128);
    g_momento      TIMESTAMP;

    -- TRUE si dos valores son distintos, tratando NULL como un valor mas:
    --   (5, 7) -> TRUE   (5, NULL) -> TRUE   (NULL, 5) -> TRUE
    --   (5, 5) -> FALSE  (NULL, NULL) -> FALSE
    -- Con un simple "a <> b", cualquier comparacion con NULL da NULL y el
    -- cambio no se auditaria.
    FUNCTION distinto(a NUMBER, b NUMBER) RETURN BOOLEAN IS
    BEGIN
        RETURN (a <> b) OR (a IS NULL AND b IS NOT NULL) OR (a IS NOT NULL AND b IS NULL);
    END distinto;

    -- ---------------- una vez, antes de la sentencia ----------------
    BEFORE STATEMENT IS
    BEGIN
        g_filas.DELETE;
        g_id_sentencia := SEQ_AUDITORIA_SENTENCIA.NEXTVAL;
        g_operacion    := CASE WHEN INSERTING THEN 'INSERT'
                               WHEN UPDATING  THEN 'UPDATE'
                               ELSE 'DELETE' END;
        g_usuario_bd   := USER;
        g_usuario_so   := SYS_CONTEXT('USERENV', 'OS_USER');
        g_equipo       := SYS_CONTEXT('USERENV', 'HOST');
        g_programa     := SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 128);
        g_momento      := SYSTIMESTAMP;
    END BEFORE STATEMENT;

    -- ---------------- por cada fila: solo se acumula ----------------
    AFTER EACH ROW IS
        i PLS_INTEGER;
    BEGIN
        -- INSERT y DELETE siempre se auditan; un UPDATE solo si algo cambio
        -- de verdad (comparacion segura frente a NULL)
        IF NOT UPDATING
           OR distinto(:OLD.precio_noche,  :NEW.precio_noche)
           OR distinto(:OLD.habitacion_id, :NEW.habitacion_id)
           OR distinto(:OLD.temporada_id,  :NEW.temporada_id) THEN
            i := g_filas.COUNT + 1;
            g_filas(i).habitacion_id   := NVL(:NEW.habitacion_id, :OLD.habitacion_id);
            g_filas(i).temporada_id    := NVL(:NEW.temporada_id,  :OLD.temporada_id);
            g_filas(i).precio_anterior := :OLD.precio_noche;   -- NULL en INSERT
            g_filas(i).precio_nuevo    := :NEW.precio_noche;   -- NULL en DELETE
        END IF;
    END AFTER EACH ROW;

    -- ---------------- una vez, despues de la sentencia ----------------
    AFTER STATEMENT IS
    BEGIN
        FORALL i IN 1 .. g_filas.COUNT
            INSERT INTO AUDITORIA_TARIFA (id_sentencia, operacion, habitacion_id,
                        temporada_id, precio_anterior, precio_nuevo, usuario_bd,
                        usuario_so, equipo, programa, fecha_hora)
            VALUES (g_id_sentencia, g_operacion, g_filas(i).habitacion_id,
                    g_filas(i).temporada_id, g_filas(i).precio_anterior,
                    g_filas(i).precio_nuevo, g_usuario_bd, g_usuario_so,
                    g_equipo, g_programa, g_momento);
        g_filas.DELETE;
    END AFTER STATEMENT;

END trg_tarifa_auditoria;
/
SHOW ERRORS TRIGGER trg_tarifa_auditoria;

-- ============================================================================
-- B) SIN SOLAPES DE HABITACION (disparador de fila, compuesto)
-- ----------------------------------------------------------------------------
-- Regla: una linea de reserva activa (reserva no CANCELADA) no puede cruzarse
-- con otra linea activa de la misma habitacion. Dos rangos [ci, co) se
-- cruzan si   linea.checkin < otra.checkout  Y  linea.checkout > otra.checkin.
-- El dia de check-out queda libre: salir el 5 y entrar el 5 si se permite.
--
-- Por que compuesto: un disparador FOR EACH ROW no puede consultar su propia
-- tabla mientras una sentencia de varias filas la esta modificando
-- (ORA-04091, tabla mutante). Oracle solo lo tolera en un INSERT ... VALUES
-- de una fila. Para que la regla valga tambien con INSERT ... SELECT y con
-- UPDATE:
--   AFTER EACH ROW  : solo guarda en una coleccion el id de cada linea
--                     insertada o modificada (no consulta la tabla).
--   AFTER STATEMENT : la tabla ya no esta mutando; para cada linea anotada
--                     busca otra linea activa de la misma habitacion que se
--                     cruce. Si la encuentra, RAISE_APPLICATION_ERROR (-20011)
--                     y Oracle deshace la sentencia COMPLETA.
-- Como la busqueda se hace con todas las filas ya escritas, tambien detecta
-- dos lineas nuevas que se cruzan entre si dentro de la misma sentencia.
--
-- Es la ultima linea de defensa: sp_crear_reserva ya valida lo mismo
-- (-20001) y bloquea la habitacion con FOR UPDATE para la concurrencia
-- (script 07), pero el disparador impide el solape aunque alguien escriba
-- directamente en la tabla, sin pasar por el paquete.
-- ============================================================================
CREATE OR REPLACE TRIGGER trg_reshab_no_solape
FOR INSERT OR UPDATE OF habitacion_id, fecha_checkin, fecha_checkout, reserva_id
ON RESERVA_HABITACION
COMPOUND TRIGGER

    TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_ids t_ids;     -- lineas insertadas o modificadas por la sentencia

    BEFORE STATEMENT IS
    BEGIN
        g_ids.DELETE;
    END BEFORE STATEMENT;

    -- por cada fila: solo se anota su id (no se consulta la tabla)
    AFTER EACH ROW IS
    BEGIN
        g_ids(g_ids.COUNT + 1) := :NEW.reserva_habitacion_id;
    END AFTER EACH ROW;

    -- una vez por sentencia: se valida con la tabla ya estable
    AFTER STATEMENT IS
        v_hab      NUMBER;
        v_ci_nueva DATE;
        v_co_nueva DATE;
        v_res_otra NUMBER;
        v_ci_otra  DATE;
        v_co_otra  DATE;
    BEGIN
        FOR i IN 1 .. g_ids.COUNT LOOP
            BEGIN
                SELECT n.habitacion_id, n.fecha_checkin, n.fecha_checkout,
                       o.reserva_id, o.fecha_checkin, o.fecha_checkout
                  INTO v_hab, v_ci_nueva, v_co_nueva, v_res_otra, v_ci_otra, v_co_otra
                  FROM RESERVA_HABITACION n
                  JOIN RESERVA rn ON rn.reserva_id = n.reserva_id
                  JOIN RESERVA_HABITACION o
                       ON  o.habitacion_id          = n.habitacion_id
                       AND o.reserva_habitacion_id <> n.reserva_habitacion_id
                       AND o.fecha_checkin          < n.fecha_checkout
                       AND o.fecha_checkout         > n.fecha_checkin
                  JOIN RESERVA ro ON ro.reserva_id = o.reserva_id
                 WHERE n.reserva_habitacion_id = g_ids(i)
                   AND rn.estado <> 'CANCELADA'      -- la linea nueva ocupa
                   AND ro.estado <> 'CANCELADA'      -- y la otra tambien
                   AND ROWNUM = 1;

                RAISE_APPLICATION_ERROR(-20011, 'Solape de reservas: la habitacion ' || v_hab ||
                    ' ya esta ocupada por la reserva ' || v_res_otra || ' (' ||
                    TO_CHAR(v_ci_otra, 'DD/MM/YYYY') || ' - ' || TO_CHAR(v_co_otra, 'DD/MM/YYYY') ||
                    ') y la linea pide ' || TO_CHAR(v_ci_nueva, 'DD/MM/YYYY') ||
                    ' - ' || TO_CHAR(v_co_nueva, 'DD/MM/YYYY') || '.');
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    NULL;   -- esta linea no se cruza con ninguna: siguiente
            END;
        END LOOP;
        g_ids.DELETE;
    END AFTER STATEMENT;

END trg_reshab_no_solape;
/
SHOW ERRORS TRIGGER trg_reshab_no_solape;

-- ============================================================================
-- C) RESENA SOLO DE UNA ESTADIA COMPLETADA (RN2, disparador de fila)
-- ----------------------------------------------------------------------------
-- Una resena se acepta solo si la reserva que la origina:
--   * existe y esta COMPLETADA,
--   * es del mismo cliente que escribe la resena, y
--   * incluye al menos una habitacion del alojamiento resenado.
-- Consulta RESERVA y RESERVA_HABITACION, no RESENA, asi que no hay tabla
-- mutante y basta un disparador de fila normal.
-- ============================================================================
CREATE OR REPLACE TRIGGER trg_resena_valida
BEFORE INSERT OR UPDATE OF cliente_id, alojamiento_id, reserva_id ON RESENA
FOR EACH ROW
DECLARE
    v_estado  RESERVA.estado%TYPE;
    v_cliente RESERVA.cliente_id%TYPE;
    v_lineas  NUMBER;
BEGIN
    BEGIN
        SELECT estado, cliente_id INTO v_estado, v_cliente
          FROM RESERVA WHERE reserva_id = :NEW.reserva_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20013, 'Resena rechazada: la reserva ' || :NEW.reserva_id || ' no existe.');
    END;

    IF v_estado <> 'COMPLETADA' THEN
        RAISE_APPLICATION_ERROR(-20013, 'Resena rechazada: la reserva ' || :NEW.reserva_id ||
            ' esta ' || v_estado || '; solo se resenan estadias completadas.');
    END IF;
    IF v_cliente <> :NEW.cliente_id THEN
        RAISE_APPLICATION_ERROR(-20013, 'Resena rechazada: la reserva ' || :NEW.reserva_id ||
            ' no pertenece al cliente ' || :NEW.cliente_id || '.');
    END IF;

    SELECT COUNT(*) INTO v_lineas
      FROM RESERVA_HABITACION rh
      JOIN HABITACION h ON h.habitacion_id = rh.habitacion_id
     WHERE rh.reserva_id = :NEW.reserva_id
       AND h.alojamiento_id = :NEW.alojamiento_id;
    IF v_lineas = 0 THEN
        RAISE_APPLICATION_ERROR(-20013, 'Resena rechazada: en la reserva ' || :NEW.reserva_id ||
            ' el cliente no se hospedo en el alojamiento ' || :NEW.alojamiento_id || '.');
    END IF;
END trg_resena_valida;
/
SHOW ERRORS TRIGGER trg_resena_valida;

-- ============================================================================
-- D) TEMPORADAS SIN CRUCES (RN7, disparador de sentencia "puro")
-- ----------------------------------------------------------------------------
-- fn_valor_estadia necesita que cada noche caiga en UNA sola temporada. Un
-- CHECK no puede comparar filas entre si, asi que despues de cada sentencia
-- sobre TEMPORADA se busca cualquier pareja de temporadas que se crucen.
-- Es AFTER ... (sin FOR EACH ROW): se ejecuta una vez por sentencia y, como
-- no usa :OLD/:NEW, puede consultar su propia tabla sin ORA-04091.
-- ============================================================================
CREATE OR REPLACE TRIGGER trg_temporada_sin_cruce
AFTER INSERT OR UPDATE OF fecha_inicio, fecha_fin ON TEMPORADA
DECLARE
    v_a VARCHAR2(120);
    v_b VARCHAR2(120);
BEGIN
    SELECT a.nombre || ' ' || a.anio, b.nombre || ' ' || b.anio
      INTO v_a, v_b
      FROM TEMPORADA a
      JOIN TEMPORADA b
           ON  a.temporada_id < b.temporada_id
           AND a.fecha_inicio <= b.fecha_fin
           AND b.fecha_inicio <= a.fecha_fin
     WHERE ROWNUM = 1;
    RAISE_APPLICATION_ERROR(-20014, 'Temporadas cruzadas: "' || v_a || '" y "' || v_b ||
        '" comparten al menos un dia.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;   -- ninguna pareja se cruza
END trg_temporada_sin_cruce;
/
SHOW ERRORS TRIGGER trg_temporada_sin_cruce;

-- Estado de los disparadores (deben quedar ENABLED / VALID)
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name, t.status,
       o.status AS compilacion
FROM   user_triggers t
JOIN   user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
ORDER BY t.table_name;
