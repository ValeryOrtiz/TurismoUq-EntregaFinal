-- TurismoUQ - 05_disparadores.sql                   (Entrega 2 - disparadores)
-- Usuario que lo ejecuta: TURISMOUQ. Ejecutar despues de 04_paquete.sql (F5).
-- ----------------------------------------------------------------------------
--   A) trg_tarifa_auditoria     nivel SENTENCIA: auditoria de cambios en TARIFA
--   B) trg_reshab_no_solape     nivel FILA (compuesto): impide reservas solapadas
--   C) trg_resena_valida        nivel FILA: solo se resena una estadia completada (RN2)
--   D) trg_temporada_sin_cruce  nivel SENTENCIA: temporadas sin cruces (RN7)
-- ----------------------------------------------------------------------------
-- CORRECCIONES TRAS LA RETROALIMENTACION DE LA ENTREGA 2:
--   * El disparador de solapes consultaba su propia tabla en un BEFORE INSERT
--     ... FOR EACH ROW: funcionaba con INSERT ... VALUES de una fila, pero un
--     INSERT ... SELECT o un UPDATE habrian fallado con ORA-04091 (tabla
--     mutante). Ahora es un disparador COMPUESTO: la seccion de fila solo
--     anota que lineas cambiaron y la validacion se hace en AFTER STATEMENT,
--     cuando la tabla ya no esta mutando. Funciona con INSERT ... VALUES,
--     INSERT ... SELECT y UPDATE de varias filas.
--   * La auditoria comparaba precio anterior y nuevo con "=", que no detecta
--     el paso de un valor a NULL (o de NULL a un valor). Ahora la comparacion
--     es segura frente a NULL.
-- ============================================================================

